#!/usr/bin/env python3
"""Turns render.mjs output into the plugin's frames.

    python3 -I optimize.py <work-dir> <frames-dir>

Each sequence gets one palette (128 colours desktop, 48 bar) computed by
libimagequant (through Pillow) over all its frames at once; every frame is then
mapped to its nearest palette entry without dithering. A shared palette and no
dither keep still parts of Mochi pixel-identical from frame to frame (no
shimmer). Frames are stored once under a content-hash name, so a still frame
shared by many sequences costs one file. Runs of identical frames inside a
sequence become one entry with a hold count.

Writes <frames-dir>/manifest.luau (what the widgets require),
<frames-dir>/manifest.json (the desktop sequences, for the coucou-mochi overlay) and
<work-dir>/index.json (the expanded frame list, for render.mjs --compare).
"""

import hashlib
import io
import json
import os
import shutil
import sys

import numpy as np
from PIL import Image

COLORS = {"desktop": 128, "bar": 48}
SUBDIR = {"desktop": "d", "bar": "b"}


def clean(im):
    """RGBA array with fully transparent pixels zeroed (their colour is noise)."""
    a = np.array(im.convert("RGBA"), dtype=np.int32)
    a[a[..., 3] == 0] = 0
    return a


def sequence_palette(arrays, colors):
    h, w = arrays[0].shape[:2]
    montage = np.concatenate(arrays, axis=0).astype(np.uint8)
    q = Image.fromarray(montage, "RGBA").quantize(colors, method=Image.Quantize.LIBIMAGEQUANT)
    pal = np.array(q.getpalette("RGBA"), dtype=np.int32).reshape(-1, 4)
    pal[pal[:, 3] == 0] = 0
    if not (pal[:, 3] == 0).any():
        # Keep an exact "nothing here" entry for the transparent background.
        pal = np.vstack([pal[: 255], [[0, 0, 0, 0]]]) if len(pal) >= 256 else np.vstack([pal, [[0, 0, 0, 0]]])
    return pal


def premultiplied(c):
    """Colours compared as they look once blended: rgb * alpha, and alpha."""
    out = c.copy()
    out[..., :3] = c[..., :3] * c[..., 3:4] // 255
    return out


def encode(a, pal):
    """Nearest palette entry per pixel (no dither), as an optimised PNG."""
    h, w = a.shape[:2]
    flat = a.reshape(-1, 4)
    uniq, inv = np.unique(flat, axis=0, return_inverse=True)
    idx = np.empty(len(uniq), dtype=np.uint8)
    pu, pp = premultiplied(uniq), premultiplied(pal)
    for i in range(0, len(uniq), 4096):
        d = ((pu[i:i + 4096, None, :] - pp[None, :, :]) ** 2).sum(-1)
        idx[i:i + 4096] = d.argmin(1)
    p = Image.frombytes("P", (w, h), idx[inv.ravel()].tobytes())
    p.putpalette(pal[:, :3].astype(np.uint8).ravel().tolist())
    p.info["transparency"] = bytes(pal[:, 3].astype(np.uint8).tolist())
    out = io.BytesIO()
    p.save(out, "PNG", optimize=True)
    return out.getvalue()


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    work, frames_dir = sys.argv[1], sys.argv[2]
    raw = json.load(open(os.path.join(work, "raw-manifest.json")))

    if os.path.isdir(frames_dir):
        shutil.rmtree(frames_dir)
    for d in SUBDIR.values():
        os.makedirs(os.path.join(frames_dir, d))

    by_raw = {}  # raw bytes digest -> relative file
    written = set()
    index = []
    seqs = {"desktop": [], "bar": []}

    for q in raw:
        mode = q["mode"]
        rels = []
        arrays = [clean(Image.open(os.path.join(work, f))) for f in q["files"]]
        pal = sequence_palette(arrays, COLORS[mode])
        for f, a in zip(q["files"], arrays):
            key = (mode, hashlib.sha256(a.tobytes()).hexdigest())
            rel = by_raw.get(key)
            if rel is None:
                png = encode(a, pal)
                name = hashlib.sha256(png).hexdigest()[:16] + ".png"
                rel = f"{SUBDIR[mode]}/{name}"
                if rel not in written:
                    with open(os.path.join(frames_dir, rel), "wb") as fh:
                        fh.write(png)
                    written.add(rel)
                by_raw[key] = rel
            rels.append(rel)
        runs = []
        for r in rels:
            if runs and runs[-1][0] == r:
                runs[-1][1] += 1
            else:
                runs.append([r, 1])
        seqs[mode].append((q, runs))
        index.append({"name": q["name"], "mode": mode, "outfit": q["outfit"], "frames": rels})

    sizes = {"desktop": round(120 * 1.5), "bar": round(32 * 2)}
    lines = [
        "-- Generated by tools/render-mochi (render.sh). Do not edit.",
        "-- Frames of the original Mochi engine (windows/src/mochi/engine.ts at 081a2ad).",
        "-- sequences[mode][\"<outfit>.<name>\"] = { fps, loop, frames = { {file, hold}, ... } }",
        "-- `hold` counts frames at `fps`; files are relative to the plugin directory.",
        "return {",
    ]
    for mode in ("desktop", "bar"):
        lines.append(f"  {mode} = {{")
        lines.append(f"    px = {sizes[mode]},")
        lines.append("    sequences = {")
        for q, runs in seqs[mode]:
            frames = ", ".join(f"{{{lua_str('frames/' + r)}, {n}}}" for r, n in runs)
            loop = "true" if q["kind"] == "loop" else "false"
            lines.append(f"      [{lua_str(q['name'])}] = {{ fps = {q['fps']:.4f}, loop = {loop}, frames = {{ {frames} }} }},")
        lines.append("    },")
        lines.append("  },")
    lines.append("}")
    with open(os.path.join(frames_dir, "manifest.luau"), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    # The same desktop sequences for the coucou-mochi overlay (overlay/), which
    # reads JSON. Sorted keys and fixed separators keep the file deterministic.
    desktop = {
        "px": sizes["desktop"],
        "sequences": {
            q["name"]: {
                "fps": round(q["fps"], 4),
                "loop": q["kind"] == "loop",
                "frames": [["frames/" + r, n] for r, n in runs],
            }
            for q, runs in seqs["desktop"]
        },
    }
    with open(os.path.join(frames_dir, "manifest.json"), "w") as fh:
        json.dump({"desktop": desktop}, fh, sort_keys=True, separators=(",", ":"))
        fh.write("\n")
    with open(os.path.join(work, "index.json"), "w") as fh:
        json.dump({"sequences": index}, fh)

    total = sum(os.path.getsize(os.path.join(frames_dir, r)) for r in written)
    print(f"{len(written)} files, {total / 1e6:.2f} MB of PNG, {sum(len(v) for v in seqs.values())} sequences")


if __name__ == "__main__":
    main()
